// Prefixa o caminho-base do site (para funcionar em GitHub Pages /repo/).
// Páginas saem sempre com barra final (/oracao/pai-nosso/), que é como o GitHub Pages
// as serve — sem a barra, cada clique passava por um redirecionamento. Arquivos (com
// extensão, como .webp), âncoras (#) e parâmetros (?dia=2) ficam como estão.
export function withBase(path: string): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  if (!path) return base || '/';
  if (/^https?:\/\//.test(path)) return path; // URL externa
  let p = path.startsWith('/') ? path : '/' + path;
  const m = /^([^?#]*)(.*)$/.exec(p);
  if (m && !m[1].endsWith('/') && !/\.[a-z0-9]+$/i.test(m[1])) p = m[1] + '/' + m[2];
  return base + p;
}
